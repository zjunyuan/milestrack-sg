// Flatten, and index by normalised name (with and without the "(branch)" part).
export const KRISPLUS_MERCHANTS = [];
for (const [category, byRate] of Object.entries(KRISPLUS_RAW)) {
  for (const [rate, names] of Object.entries(byRate)) {
    for (const name of names) {
      const full = normalizeText(name);
      const base = normalizeText(name.replace(/\s*\([^)]*\)\s*/g, " "));
      KRISPLUS_MERCHANTS.push({ name, category, mpd: Number(rate), full, base, baseTokens: base.split(" ").filter(Boolean) });
    }
  }
}

// Finds Kris+ merchants for text typed into the recommender. Exact name first; otherwise the typed text must be the start of a name (4+ letters),
// contain a whole name (6+ letters), or share all its words with a name (2+ words). Returns up to 4 matches, best first.
export function findKrisPlusMerchants(text) {
  const q = normalizeText(text || "");
  if (q.length < 3 || /^\d+$/.test(q)) return [];
  const exact = KRISPLUS_MERCHANTS.filter(m => m.full === q || m.base === q);
  if (exact.length) return exact.slice(0, 4);
  const qt = q.split(" ").filter(Boolean);
  const hit = KRISPLUS_MERCHANTS.filter(m => {
    if (q.length >= 4 && (m.base.startsWith(q) || m.full.startsWith(q))) return true;
    if (m.base.length >= 6 && (" " + q + " ").includes(" " + m.base + " ")) return true;
    return qt.length >= 2 && qt.every(t => m.baseTokens.includes(t));
  });
  return hit.sort((a, b) => b.mpd - a.mpd).slice(0, 4);
}

